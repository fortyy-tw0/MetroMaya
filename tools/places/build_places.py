#!/usr/bin/env python3
"""Builds src/main/resources/static/js/ncr-places.js: barangays and ZIP codes for each Metro Manila city.

Sources (npm packages, read as data only):
  psgc 2.2.0         dist/data/barangays.json   PSA's Philippine Standard Geographic Code list
  zipcodes-ph 1.1.2  build/zipcodes.json        PHLPost ZIP code directory (ZIP -> area name)

Usage:
  mkdir -p /tmp/places && cd /tmp/places && npm pack psgc@2.2.0 zipcodes-ph@1.1.2 && for f in *.tgz; do mkdir -p "${f%.tgz}" && tar xzf "$f" -C "${f%.tgz}"; done
  python3 -I tools/places/build_places.py /tmp/places/psgc-2.2.0/package /tmp/places/zipcodes-ph-1.1.2/package

Corrections applied on top of the sources:
  * The 10 "EMBO" barangays moved from Makati to Taguig (Supreme Court ruling, final in 2023; PSA updated
    the PSGC in 2024), along with the Fort Bonifacio and EMBO-area ZIP codes.
  * Manila's barangays are grouped by district (Tondo, Sampaloc, ...), which also picks their ZIP code.
"""
import json, re, sys

psgc_dir, zip_dir = sys.argv[1], sys.argv[2]
barangays = json.load(open(psgc_dir + '/dist/data/barangays.json'))
zips = json.load(open(zip_dir + '/build/zipcodes.json'))

MANILA_DISTRICTS = {'Binondo', 'Ermita', 'Intramuros', 'Malate', 'Paco', 'Pandacan', 'Port Area', 'Quiapo',
                    'Sampaloc', 'San Miguel', 'San Nicolas', 'Santa Ana', 'Santa Cruz', 'Tondo I Ii'}
CITY_OF = {
    'Caloocan City': 'caloocan', 'City Of Las Pinas': 'las-pinas', 'City Of Makati': 'makati',
    'City Of Malabon': 'malabon', 'City Of Mandaluyong': 'mandaluyong', 'City Of Marikina': 'marikina',
    'City Of Muntinlupa': 'muntinlupa', 'City Of Navotas': 'navotas', 'City Of Paranaque': 'paranaque',
    'Pasay City': 'pasay', 'City Of Pasig': 'pasig', 'Pateros': 'pateros', 'Quezon City': 'quezon-city',
    'City Of San Juan': 'san-juan', 'Taguig City': 'taguig', 'City Of Valenzuela': 'valenzuela',
}
EMBO = {'Cembo', 'Comembo', 'East Rembo', 'Pembo', 'Pitogo', 'Post Proper Northside', 'Post Proper Southside',
        'Rizal', 'South Cembo', 'West Rembo'}
ZIP_RANGES = {
    'manila': (1000, 1018), 'quezon-city': (1100, 1128), 'makati': (1200, 1235), 'pasay': (1300, 1309),
    'caloocan': (1400, 1428), 'valenzuela': (1440, 1448), 'malabon': (1470, 1480), 'navotas': (1485, 1490),
    'san-juan': (1500, 1504), 'mandaluyong': (1550, 1556), 'pasig': (1600, 1612), 'pateros': (1620, 1621),
    'taguig': (1630, 1638), 'paranaque': (1700, 1720), 'las-pinas': (1740, 1752), 'muntinlupa': (1770, 1781),
    'marikina': (1800, 1811),
}
TO_TAGUIG = {'1201', '1202', '1214', '1215', '1216', '1217', '1218'}   # Fort Bonifacio and EMBO-area ZIPs
BOTH = {'1213'}                                                        # Pinagkaisahan (Makati) - Pitogo (Taguig)
# Manila ZIP codes by district (district name -> ZIPs that cover it)
MANILA_ZIPS = {
    'Binondo': ['1006'], 'Ermita': ['1000'], 'Intramuros': ['1002'], 'Malate': ['1004'], 'Paco': ['1007'],
    'Pandacan': ['1011'], 'Port Area': ['1018'], 'Quiapo': ['1001'], 'Sampaloc': ['1008', '1015', '1016'],
    'San Miguel': ['1005'], 'San Nicolas': ['1010'], 'Santa Ana': ['1009', '1017'], 'Santa Cruz': ['1003', '1014'],
    'Tondo': ['1012', '1013'],
}

def nat_key(name):
    return [int(t) if t.isdigit() else t.lower() for t in re.split(r'(\d+)', name)]

places = {cid: {'barangays': [], 'zips': []} for cid in ZIP_RANGES}
for b in barangays:
    if not str(b['code']).zfill(9).startswith('13'):
        continue
    cm, name = b['citymun'], b['name'].strip()
    if cm in MANILA_DISTRICTS:
        district = 'Tondo' if cm.startswith('Tondo') else cm
        places['manila']['barangays'].append({'name': name, 'district': district})
        continue
    cid = CITY_OF[cm]
    if cid == 'makati' and name in EMBO:
        cid = 'taguig'
    places[cid]['barangays'].append({'name': name})

for cid, (lo, hi) in ZIP_RANGES.items():
    for code in sorted(zips):
        if not (lo <= int(code) <= hi):
            continue
        area = zips[code]
        area = ', '.join(area) if isinstance(area, list) else area
        owner = 'taguig' if code in TO_TAGUIG else cid
        places[owner]['zips'].append({'code': code, 'area': area})
        if code in BOTH:
            places['taguig']['zips'].append({'code': code, 'area': area})
places['taguig']['zips'].sort(key=lambda z: z['code'])

for cid, p in places.items():
    p['barangays'].sort(key=lambda b: (b.get('district', ''), nat_key(b['name'])))
for b in places['manila']['barangays']:
    b['zips'] = MANILA_ZIPS[b['district']]

out = ('// Generated by tools/places/build_places.py from the PSA PSGC list and the PHLPost ZIP directory.\n'
       '// Do not edit by hand; rerun the script instead.\n'
       'const NCR_PLACES = ' + json.dumps(places, ensure_ascii=False, separators=(',', ':')) + ';\n')
dst = 'src/main/resources/static/js/ncr-places.js'
open(dst, 'w', encoding='utf-8').write(out)
for cid, p in places.items():
    print(f"{cid:12s} {len(p['barangays']):4d} barangays  {len(p['zips']):3d} ZIPs")
print('wrote', dst, len(out.encode()), 'bytes')
